// Generates `src/reka/<family>.ts`: the component families of Reka UI that the UI imports. They are built into
// `dist/reka`, so a site doesn't install Reka UI.
//
//   node scripts/gen-reka.mjs
//
// Import a primitive in the UI from Reka UI, `import { DialogRoot } from "reka-ui"`, then run this: the import
// becomes one of `@fumapress/vue/reka/dialog`, and the family is added with all of its exports.
import { mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE = "reka-ui";
const ENTRY = "@fumapress/vue/reka/";
/** what the UI imports that belongs to no family, like a composable */
const SHARED = "shared";
const root = fileURLToPath(new URL("..", import.meta.url));
const outDir = path.join(root, "src/reka");
const reka = path.dirname(createRequire(import.meta.url).resolve(`${SOURCE}/package.json`));
const { version } = JSON.parse(readFileSync(path.join(reka, "package.json"), "utf8"));

// a family is a folder of Reka UI's build, and its exports start with its name: `Dialog`, `DialogRoot`
const families = readdirSync(path.join(reka, "dist"))
  .filter((name) => /^[A-Z]/.test(name) && statSync(path.join(reka, "dist", name)).isDirectory())
  .sort((a, b) => b.length - a.length);
const familyOf = (name) =>
  families.find((family) => name.replace(/^inject/, "").startsWith(family));
const fileOf = (family) => family.replace(/([a-z])([A-Z])/g, "$1-$2").toLowerCase();

// every export of Reka UI, and whether it is a type: a name of its types that the module doesn't have
const values = new Set(Object.keys(await import(SOURCE)));
const exported = new Map();
const types = readFileSync(path.join(reka, "dist/index.d.ts"), "utf8");
for (const [, list] of types.matchAll(/^export \{([^}]+)\}/gm)) {
  for (const item of list.split(",")) {
    const name = item
      .trim()
      .split(/\s+as\s+/)
      .at(-1);
    if (name) exported.set(name, !values.has(name));
  }
}

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const file = path.join(dir, name);
    if (statSync(file).isDirectory()) walk(file, out);
    else if (/\.(vue|ts)$/.test(name)) out.push(file);
  }
  return out;
}

// the names the UI imports, from Reka UI or from the entries this writes: an import of Reka UI is split by family
const STATEMENT = /\b(import|export)(\s+type)?\s*\{([^}]*)\}\s*from\s*"([^"]+)";?/g;
const used = new Map();
function use(name) {
  if (!exported.has(name)) throw new Error(`"${name}" is not an export of ${SOURCE} ${version}.`);
  const file = fileOf(familyOf(name) ?? SHARED);
  used.set(file, (used.get(file) ?? new Set()).add(name));
  return file;
}

for (const file of [...walk(path.join(root, "ui")), ...walk(path.join(root, "theme"))]) {
  const code = readFileSync(file, "utf8");
  const next = code.replace(STATEMENT, (match, keyword, type = "", list, specifier) => {
    if (specifier !== SOURCE && !specifier.startsWith(ENTRY)) return match;
    const byFile = new Map();
    for (const item of list.split(",").map((item) => item.trim())) {
      if (!item) continue;
      const [, name] = /^(?:type\s+)?(\w+)/.exec(item);
      const target = use(name);
      byFile.set(target, [...(byFile.get(target) ?? []), item]);
    }
    if (specifier !== SOURCE) return match;
    return [...byFile]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(
        ([target, items]) => `${keyword}${type} { ${items.join(", ")} } from "${ENTRY}${target}";`,
      )
      .join("\n");
  });
  if (next !== code) writeFileSync(file, next);
}

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
for (const [file, names] of used) {
  // a family comes whole, so a copy of a module can use the parts the UI doesn't
  const all =
    file === SHARED
      ? [...names]
      : [...exported.keys()].filter((name) => fileOf(familyOf(name) ?? SHARED) === file);
  const list = all.sort().map((name) => (exported.get(name) ? `type ${name}` : name));
  writeFileSync(
    path.join(outDir, `${file}.ts`),
    `// Generated by scripts/gen-reka.mjs from ${SOURCE} ${version} (MIT License, UnoVue). Don't edit it:
// import from "${SOURCE}" in the UI and run the script.
export {
${list.map((name) => `  ${name},`).join("\n")}
} from "${SOURCE}";
`,
  );
}
console.log(`${used.size} families: ${[...used.keys()].sort().join(", ")}`);
