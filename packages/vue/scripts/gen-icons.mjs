// Generates `ui/icons/index.ts`: the icons of Lucide that the UI imports, so a site doesn't install the whole set.
//
//   node scripts/gen-icons.mjs
//
// Import an icon in the UI as in Fumadocs UI, `import { Star } from "@lucide/vue"`, then run this: the import
// becomes one of `ui/icons`, and the icon is added to it.
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const PACKAGE = "@lucide/vue";
const root = fileURLToPath(new URL("..", import.meta.url));
const iconsDir = path.join(root, "ui/icons");
const lucide = path.dirname(createRequire(import.meta.url).resolve(`${PACKAGE}/package.json`));
const { version } = JSON.parse(readFileSync(path.join(lucide, "package.json"), "utf8"));

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const file = path.join(dir, name);
    if (file === iconsDir) continue;
    if (statSync(file).isDirectory()) walk(file, out);
    else if (/\.(vue|ts)$/.test(name)) out.push(file);
  }
  return out;
}

// the names the UI imports, from Lucide or from the module this writes
const IMPORT = /import\s*\{([^}]*)\}\s*from\s*"([^"]+)"/g;
const used = new Set();
for (const file of [...walk(path.join(root, "ui")), ...walk(path.join(root, "theme"))]) {
  const code = readFileSync(file, "utf8");
  let relative = path.relative(path.dirname(file), iconsDir).split(path.sep).join("/");
  if (!relative.startsWith(".")) relative = `./${relative}`;

  const next = code.replace(IMPORT, (match, names, specifier) => {
    const isIcons =
      specifier === PACKAGE ||
      (specifier.startsWith(".") && path.resolve(path.dirname(file), specifier) === iconsDir);
    if (!isIcons) return match;
    for (const name of names.split(",")) {
      const [imported] = name.trim().split(/\s+as\s+/);
      if (imported && !imported.startsWith("type ")) used.add(imported);
    }
    return match.replace(`"${specifier}"`, `"${relative}"`);
  });
  if (next !== code) writeFileSync(file, next);
}

// each export of Lucide is a name for an icon file
const files = new Map();
const index = readFileSync(path.join(lucide, "dist/esm/lucide-vue.mjs"), "utf8");
for (const [, names, file] of index.matchAll(
  /export \{([^}]+)\} from '\.\/icons\/([\w-]+)\.mjs';/g,
)) {
  for (const [, name] of names.matchAll(/default as (\w+)/g)) files.set(name, file);
}

const byFile = new Map();
for (const name of [...used].sort()) {
  const file = files.get(name);
  if (!file) throw new Error(`"${name}" is not an icon of ${PACKAGE} ${version}.`);
  byFile.set(file, [...(byFile.get(file) ?? []), name]);
}

const lines = [];
for (const [file, names] of [...byFile].sort(([a], [b]) => a.localeCompare(b))) {
  const { __iconData } = await import(
    pathToFileURL(path.join(lucide, `dist/esm/icons/${file}.mjs`)).href
  );
  // the elements, without the keys React needs
  const node = __iconData.node.map(([tag, attrs]) => [
    tag,
    Object.fromEntries(Object.entries(attrs).filter(([name]) => name !== "key")),
  ]);
  const [first, ...aliases] = names;
  lines.push(
    `export const ${first} = createIcon(${JSON.stringify(__iconData.name)}, ${JSON.stringify(node)});`,
  );
  if (aliases.length > 0) {
    lines.push(`export { ${aliases.map((alias) => `${first} as ${alias}`).join(", ")} };`);
  }
}

writeFileSync(
  path.join(iconsDir, "index.ts"),
  `// Generated by scripts/gen-icons.mjs from ${PACKAGE} ${version} (ISC License, Lucide Contributors): the icons the UI
// uses. Don't edit it: import an icon in the UI and run the script.
import { createIcon } from "./create-icon";

export { createIcon, type IconNode, type IconProps } from "./create-icon";

${lines.join("\n")}
`,
);
console.log(`${used.size} names, ${byFile.size} icons`);
