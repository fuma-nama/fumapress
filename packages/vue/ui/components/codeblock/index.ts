/**
 * `title` and `icon` are also slots of the same name. The slot `Actions` replaces the element of the copy button: it
 * receives its `class`, and the copy button as the component `children`.
 *
 * `data-line-numbers` (show line numbers) and `data-line-numbers-start` (1 by default) are attributes.
 */
export interface CodeBlockProps {
  class?: HTMLAttributes["class"];

  title?: string | VNode;

  /**
   * Icon of code block
   *
   * When passed as a string, it assumes the value is the HTML of icon
   */
  icon?: string | VNode;

  /**
   * Allow to copy code with copy button
   *
   * @defaultValue true
   */
  allowCopy?: boolean | "true" | "false";

  /**
   * Keep original background color generated by Shiki or Rehype Code
   *
   * @defaultValue false
   */
  keepBackground?: boolean;

  viewportProps?: HTMLAttributes;
}
